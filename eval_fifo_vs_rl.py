import csv
import os
from collections import Counter

import matplotlib.pyplot as plt


DATA_DIR = "data"
PLOTS_DIR = "data/plots"

FIFO_DECISIONS = os.path.join(DATA_DIR, "fifo_metrics.csv")
RL_DECISIONS = os.path.join(DATA_DIR, "rl_metrics.csv")

FIFO_TRAFFIC = os.path.join(DATA_DIR, "fifo_traffic_metrics.csv")
RL_TRAFFIC = os.path.join(DATA_DIR, "rl_traffic_metrics.csv")


def ensure_dirs():
    os.makedirs(PLOTS_DIR, exist_ok=True)


def read_controller_decisions(path):
    """
    Reads controller path decisions.

    Expected new format from ryu_common.py:
        timestamp,policy,proto,src,dst,src_port,dst_port,path

    Only TCP decisions are used for TrafPy/iperf path usage.
    """

    if not os.path.exists(path):
        print(f"[WARN] Missing controller decision file: {path}")
        return []

    rows = []

    with open(path, "r") as f:
        reader = csv.DictReader(f)

        for row in reader:
            proto = row.get("proto", "").lower()
            path_name = row.get("path", "")

            # Only count actual TrafPy/iperf TCP flow decisions.
            if proto != "tcp":
                continue

            if path_name not in ["upper", "lower"]:
                continue

            rows.append({
                "timestamp": row.get("timestamp", ""),
                "policy": row.get("policy", ""),
                "proto": proto,
                "src": row.get("src", ""),
                "dst": row.get("dst", ""),
                "src_port": row.get("src_port", ""),
                "dst_port": row.get("dst_port", ""),
                "path": path_name,
            })

    return rows


def summarize_path_usage(decision_rows):
    paths = [row["path"] for row in decision_rows]

    counts = Counter(paths)
    total = sum(counts.values())

    if total == 0:
        return {
            "total_flows": 0,
            "upper": 0,
            "lower": 0,
            "upper_percent": 0.0,
            "lower_percent": 0.0,
        }

    return {
        "total_flows": total,
        "upper": counts["upper"],
        "lower": counts["lower"],
        "upper_percent": round((counts["upper"] / total) * 100, 2),
        "lower_percent": round((counts["lower"] / total) * 100, 2),
    }


def read_traffic_metrics(path):
    """
    Reads traffic metrics generated by automated_traffic_tests.py.

    Expected format:
        policy,flow_id,src,dst,size_kb,throughput_mbps,latency_ms,packet_loss_percent
    """

    if not os.path.exists(path):
        print(f"[WARN] Missing traffic metrics file: {path}")
        return []

    rows = []

    with open(path, "r") as f:
        reader = csv.DictReader(f)

        for row in reader:
            try:
                rows.append({
                    "policy": row["policy"],
                    "flow_id": int(row["flow_id"]),
                    "src": row["src"],
                    "dst": row["dst"],
                    "size_kb": float(row["size_kb"]),
                    "throughput_mbps": float(row["throughput_mbps"]),
                    "latency_ms": float(row["latency_ms"]),
                    "packet_loss_percent": float(row["packet_loss_percent"]),
                })
            except (KeyError, ValueError) as e:
                print(f"[WARN] Skipping bad traffic row in {path}: {row} ({e})")

    rows.sort(key=lambda r: r["flow_id"])
    return rows


def average_metric(rows, metric):
    if not rows:
        return 0.0

    return sum(row[metric] for row in rows) / len(rows)


def summarize_traffic(rows):
    return {
        "total_tests": len(rows),
        "average_throughput_mbps": average_metric(rows, "throughput_mbps"),
        "average_latency_ms": average_metric(rows, "latency_ms"),
        "average_packet_loss_percent": average_metric(rows, "packet_loss_percent"),
    }


def print_path_summary(name, summary):
    print()
    print(f"{name} Controller TCP Path Decisions")
    print("-" * 45)
    print(f"TCP decisions: {summary['total_flows']}")
    print(f"Upper path:    {summary['upper']} ({summary['upper_percent']}%)")
    print(f"Lower path:    {summary['lower']} ({summary['lower_percent']}%)")


def print_traffic_summary(name, summary):
    print()
    print(f"{name} Traffic Metrics")
    print("-" * 45)
    print(f"Traffic tests:        {summary['total_tests']}")
    print(f"Average throughput:   {summary['average_throughput_mbps']:.3f} Mbps")
    print(f"Average latency:      {summary['average_latency_ms']:.3f} ms")
    print(f"Average packet loss:  {summary['average_packet_loss_percent']:.3f}%")


def validate_counts(name, decision_rows, traffic_rows):
    """
    Warns if controller path decisions do not align with traffic tests.

    Ideally:
        number of TCP controller decisions ~= number of TrafPy iperf flows

    If these are very different, Ryu may still not be deciding per TrafPy flow.
    """

    decision_count = len(decision_rows)
    traffic_count = len(traffic_rows)

    print()
    print(f"{name} Validation")
    print("-" * 45)
    print(f"TCP controller decisions: {decision_count}")
    print(f"Traffic metric rows:      {traffic_count}")

    if traffic_count == 0:
        print("[WARN] No traffic rows found.")
        return

    ratio = decision_count / traffic_count

    if ratio < 0.8:
        print("[WARN] Controller decisions are much lower than traffic rows.")
        print("       Ryu may not be making one decision per TrafPy TCP flow.")
    elif ratio > 1.5:
        print("[WARN] Controller decisions are much higher than traffic rows.")
        print("       Ryu may be counting TCP handshakes/reverse flows separately.")
    else:
        print("[OK] Controller decisions roughly match traffic tests.")


def plot_path_usage(fifo_summary, rl_summary):
    labels = ["Upper Path", "Lower Path"]

    fifo_values = [
        fifo_summary["upper"],
        fifo_summary["lower"],
    ]

    rl_values = [
        rl_summary["upper"],
        rl_summary["lower"],
    ]

    x = range(len(labels))

    plt.figure()
    plt.bar([i - 0.2 for i in x], fifo_values, width=0.4, label="FIFO")
    plt.bar([i + 0.2 for i in x], rl_values, width=0.4, label="RL")
    plt.xticks(list(x), labels)
    plt.ylabel("TCP Flow Decisions")
    plt.title("FIFO vs RL TCP Path Decisions")
    plt.legend()

    plt.savefig(
        os.path.join(PLOTS_DIR, "fifo_vs_rl_path_usage.png"),
        bbox_inches="tight",
    )

    plt.close()


def plot_metric_line_graph(fifo_rows, rl_rows, metric, ylabel, title, filename):
    fifo_values = [row[metric] for row in fifo_rows]
    rl_values = [row[metric] for row in rl_rows]

    fifo_x = [row["flow_id"] for row in fifo_rows]
    rl_x = [row["flow_id"] for row in rl_rows]

    plt.figure()

    if fifo_values:
        plt.plot(fifo_x, fifo_values, marker="o", label="FIFO")

    if rl_values:
        plt.plot(rl_x, rl_values, marker="o", label="RL")

    plt.xlabel("TrafPy Flow ID")
    plt.ylabel(ylabel)
    plt.title(title)
    plt.legend()

    plt.savefig(
        os.path.join(PLOTS_DIR, filename),
        bbox_inches="tight",
    )

    plt.close()


def write_summary_csv(fifo_path_summary, rl_path_summary, fifo_traffic_summary, rl_traffic_summary):
    output_file = os.path.join(DATA_DIR, "fifo_vs_rl_summary.csv")

    with open(output_file, "w", newline="") as f:
        writer = csv.writer(f)

        writer.writerow([
            "policy",
            "tcp_decisions",
            "upper_decisions",
            "lower_decisions",
            "upper_percent",
            "lower_percent",
            "traffic_tests",
            "average_throughput_mbps",
            "average_latency_ms",
            "average_packet_loss_percent",
        ])

        writer.writerow([
            "FIFO",
            fifo_path_summary["total_flows"],
            fifo_path_summary["upper"],
            fifo_path_summary["lower"],
            fifo_path_summary["upper_percent"],
            fifo_path_summary["lower_percent"],
            fifo_traffic_summary["total_tests"],
            fifo_traffic_summary["average_throughput_mbps"],
            fifo_traffic_summary["average_latency_ms"],
            fifo_traffic_summary["average_packet_loss_percent"],
        ])

        writer.writerow([
            "RL",
            rl_path_summary["total_flows"],
            rl_path_summary["upper"],
            rl_path_summary["lower"],
            rl_path_summary["upper_percent"],
            rl_path_summary["lower_percent"],
            rl_traffic_summary["total_tests"],
            rl_traffic_summary["average_throughput_mbps"],
            rl_traffic_summary["average_latency_ms"],
            rl_traffic_summary["average_packet_loss_percent"],
        ])

    print()
    print(f"Saved summary CSV: {output_file}")


def main():
    ensure_dirs()

    fifo_decisions = read_controller_decisions(FIFO_DECISIONS)
    rl_decisions = read_controller_decisions(RL_DECISIONS)

    fifo_path_summary = summarize_path_usage(fifo_decisions)
    rl_path_summary = summarize_path_usage(rl_decisions)

    fifo_rows = read_traffic_metrics(FIFO_TRAFFIC)
    rl_rows = read_traffic_metrics(RL_TRAFFIC)

    fifo_traffic_summary = summarize_traffic(fifo_rows)
    rl_traffic_summary = summarize_traffic(rl_rows)

    print_path_summary("FIFO", fifo_path_summary)
    print_path_summary("RL", rl_path_summary)

    print_traffic_summary("FIFO", fifo_traffic_summary)
    print_traffic_summary("RL", rl_traffic_summary)

    validate_counts("FIFO", fifo_decisions, fifo_rows)
    validate_counts("RL", rl_decisions, rl_rows)

    plot_path_usage(fifo_path_summary, rl_path_summary)

    plot_metric_line_graph(
        fifo_rows,
        rl_rows,
        metric="throughput_mbps",
        ylabel="Throughput (Mbps)",
        title="FIFO vs RL Throughput",
        filename="fifo_vs_rl_throughput.png",
    )

    plot_metric_line_graph(
        fifo_rows,
        rl_rows,
        metric="latency_ms",
        ylabel="Latency (ms)",
        title="FIFO vs RL Latency",
        filename="fifo_vs_rl_latency.png",
    )

    plot_metric_line_graph(
        fifo_rows,
        rl_rows,
        metric="packet_loss_percent",
        ylabel="Packet Loss (%)",
        title="FIFO vs RL Packet Loss",
        filename="fifo_vs_rl_packet_loss.png",
    )

    write_summary_csv(
        fifo_path_summary,
        rl_path_summary,
        fifo_traffic_summary,
        rl_traffic_summary,
    )

    print()
    print("Saved plots:")
    print("- data/plots/fifo_vs_rl_path_usage.png")
    print("- data/plots/fifo_vs_rl_throughput.png")
    print("- data/plots/fifo_vs_rl_latency.png")
    print("- data/plots/fifo_vs_rl_packet_loss.png")


if __name__ == "__main__":
    main()
